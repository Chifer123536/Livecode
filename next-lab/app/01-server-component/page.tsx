import { getPosts } from '@/app/lib/db'

/**
 * ДЕМО 01 — СЕРВЕРНЫЙ КОМПОНЕНТ
 *
 * Компонент объявлен как `async` и данные берёт прямо в теле — без useEffect,
 * без useState, без состояния загрузки. Всё это выполняется на сервере ДО отправки HTML.
 *
 * Что отсюда следует:
 *  - секреты и токены здесь безопасны: код не попадает в бандл браузера;
 *  - можно ходить в базу напрямую, без промежуточного API-роута;
 *  - нет «водопада» запросов, как при загрузке из useEffect после монтирования;
 *  - взамен нельзя useState, useEffect, onClick и обращение к window.
 *
 * Главный вопрос на собесе: почему серверный компонент по умолчанию, а клиентский — по требованию?
 * Ответ: меньше JavaScript у пользователя. Клиентский компонент тянет за собой свой код и всю
 * свою ветку зависимостей в бандл, серверный — ноль байт.
 */

// Рендерим на каждый запрос, чтобы время отрисовки действительно менялось.
export const dynamic = 'force-dynamic'

export default async function ServerComponentDemo() {
	const posts = await getPosts(300)
	const renderedAt = new Date().toLocaleTimeString('ru-RU')

	return (
		<>
			<h1>Серверный компонент</h1>
			<p className="lead">Данные получены на сервере во время рендера. В бандл этот код не попал.</p>

			<div className="note">
				Отрисовано на сервере в {renderedAt}. Обнови страницу — время изменится, потому что
				<code>getPosts</code> не закэширован и страница рендерится на каждый запрос.
			</div>

			{posts.map(post => (
				<div className="card" key={post.id}>
					<strong>{post.title}</strong>
					<div style={{ color: 'var(--muted)' }}>{post.body}</div>
				</div>
			))}

			<h2>Что проверить руками</h2>
			<ul>
				<li>Открой исходный код страницы (Ctrl+U) — заголовки постов уже в HTML.</li>
				<li>
					Добавь <code>console.log</code> в компонент: он появится в терминале, где запущен
					<code>yarn dev</code>, а не в консоли браузера.
				</li>
				<li>
					Попробуй добавить <code>useState</code> — получишь ошибку сборки. Это и есть граница
					сервер/клиент.
				</li>
			</ul>
		</>
	)
}
