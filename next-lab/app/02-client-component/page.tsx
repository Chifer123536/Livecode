import { getPosts } from '@/app/lib/db'
import { Counter } from './counter'

/**
 * ДЕМО 02 — ГРАНИЦА СЕРВЕР / КЛИЕНТ
 *
 * Сама страница осталась СЕРВЕРНОЙ: она ходит за данными и рендерит разметку.
 * Интерактивный кусок вынесен в отдельный файл с 'use client'.
 *
 * Ключевой приём — КОМПОЗИЦИЯ ЧЕРЕЗ children.
 * Серверный компонент нельзя импортировать внутрь клиентского: клиентский модуль
 * собирается для браузера, а серверный там выполнить невозможно.
 * Зато можно передать уже отрендеренный серверный элемент КАК ПРОПС (обычно children) —
 * клиентская обёртка просто выведет готовое дерево, не зная, что внутри.
 *
 * Что можно передать через границу: только сериализуемое.
 * Строки, числа, массивы, обычные объекты, Date, Map, Set, промисы, JSX.
 * Нельзя: функции (кроме Server Actions), классы, Symbol.
 */

export default async function ClientBoundaryDemo() {
	const posts = await getPosts()

	return (
		<>
			<h1>Клиентский компонент</h1>
			<p className="lead">Серверная страница плюс маленький интерактивный островок.</p>

			<Counter />

			<div className="note">
				Считать в бандл: сюда попал только <code>counter.tsx</code>. Разметка списка ниже
				отрисована на сервере и весит ноль байт JavaScript.
			</div>

			<h2>Данные с сервера</h2>
			{posts.map(post => (
				<div className="card" key={post.id}>
					<strong>{post.title}</strong>
				</div>
			))}

			<h2>Правила границы</h2>
			<ul>
				<li>
					<code>'use client'</code> — первая строка файла, до импортов.
				</li>
				<li>Директива заразна вниз: всё, что импортирует клиентский модуль, тоже становится клиентским.</li>
				<li>
					Серверный компонент внутрь клиентского — только через <code>children</code> или другой пропс.
				</li>
				<li>Через границу летит только сериализуемое. Функцию передать нельзя — кроме Server Action.</li>
				<li>
					Клиентский компонент всё равно рендерится на сервере для первого HTML. Если нужен именно
					браузер (доступ к <code>window</code>), проверяй в <code>useEffect</code>.
				</li>
			</ul>
		</>
	)
}
