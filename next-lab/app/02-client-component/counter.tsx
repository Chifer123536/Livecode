'use client'

import { useState } from 'react'

/**
 * Директива 'use client' стоит ПЕРВОЙ строкой файла.
 * Она не означает «рендерить только в браузере»: компонент всё равно проходит SSR,
 * а потом гидрируется на клиенте. Она означает «этот модуль и всё, что он импортирует,
 * попадает в бандл браузера и умеет быть интерактивным».
 *
 * Граница ставится максимально глубоко: один маленький клиентский островок
 * вместо целой страницы, помеченной 'use client'.
 */
export function Counter() {
	const [count, setCount] = useState(0)

	return (
		<div className="card">
			<p>Счёт: {count}</p>
			<button onClick={() => setCount(c => c + 1)}>+1</button>
		</div>
	)
}
